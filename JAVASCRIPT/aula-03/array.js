// uma caixa com varios elementos

//               0        1          2       3
let frutas = ['maçã', 'banana', 'laranja', 'uva'];

// mostra o item q o num representa
console.log(frutas[0]);  // 'maçã'
console.log(frutas[2]);  // 'laranja'

// é uma conta matematica q mostra o ultimo item (pega o total de intens (ex:3) e diminui por 1)
console.log(frutas[frutas.length - 1]); // 'uva'

